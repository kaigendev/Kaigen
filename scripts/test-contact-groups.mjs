import assert from "node:assert/strict";
import { importTypeScriptModule } from "./import-typescript-module.mjs";

const groups = await importTypeScriptModule(new URL("../src/contactGroups.ts", import.meta.url));
const { UNGROUPED_ID: U, normalizeContactGroups: normalize, createContactGroup: create, renameContactGroup: rename, assignContactGroup: assign, deleteContactGroup: remove, toggleContactGroup: toggle, reorderContactGroup: reorder, removeContactFromGroups: removeContact, groupNameError } = groups;
let assertions = 0;
const eq = (actual, expected, message) => { assertions++; assert.deepEqual(actual, expected, message); };
const same = (actual, expected, message) => { assertions++; assert.equal(actual, expected, message); };
const A = "A".repeat(64), B = "B".repeat(64), C = "C".repeat(64);
const freeze = value => { if (value && typeof value === "object") { Object.values(value).forEach(freeze); Object.freeze(value); } return value; };
const empty = freeze(normalize(undefined));
eq(empty, { version: 1, enabled: false, groups: [], assignments: {}, order: [U], collapsed: [] }, "old profiles start with grouping disabled");
eq(normalize({ version: 2, enabled: true }), empty, "future unknown schemas do not reinterpret data");
let state = create(empty, A.toLowerCase(), "work", " Работа ");
eq(state.groups, [{ id: "work", name: "Работа" }]);
eq(state.assignments, { [A]: "work" }, "identities use uppercase public keys, never recycled friend numbers");
same(state.enabled, false, "creating a group preserves display preference");
same(create(state, B, "other", "работа"), state, "duplicate case-insensitive names are rejected atomically");
for (const name of ["", "  ", " Без группы ", "UNGROUPED"]) same(create(state, B, "other", name), state, "empty and reserved names leave state unchanged");
same(create(state, "friend-number-1", "other", "Friends"), state);
same(create(state, B, U, "Friends"), state);
same(create(state, B, "work", "Friends"), state);
same(create(state, B, "   ", "Friends"), state);
same(groupNameError(state, " "), "empty");
same(groupNameError(state, "Без группы"), "reserved");
same(groupNameError(state, "РАБОТА"), "duplicate");
same(groupNameError(state, "РАБОТА", "work"), null);
state = freeze({ ...state, enabled: true });
let expanded = create(state, B, "friends", "Друзья");
expanded = assign(expanded, C, "friends");
expanded = toggle(toggle(expanded, U), "friends");
eq(expanded.order, [U, "work", "friends"]);
eq(expanded.collapsed, [U, "friends"]);
let moved = reorder(expanded, "friends", U);
eq(moved.order, ["friends", U, "work"], "system group can move within user order");
eq(reorder(moved, U, "friends").order, [U, "friends", "work"]);
eq(moved.collapsed, expanded.collapsed, "reordering does not collapse or expand groups");
same(reorder(moved, "unknown", U), moved);
same(reorder(moved, "friends", "friends"), moved);
same(rename(moved, U, "Other"), moved);
same(remove(moved, U), moved);
same(toggle(moved, "unknown"), moved);
same(assign(moved, A, "unknown"), moved);
same(rename(moved, "friends", "работа"), moved);
eq(rename(moved, "friends", " Friends ").groups.find(group => group.id === "friends").name, "Friends");
same(rename(moved, "friends", "Друзья"), moved);
let departed = assign(moved, A, "friends");
eq(departed.groups.map(group => group.id), ["friends"], "moving last contact prunes the source group");
eq(departed.order, ["friends", U]);
same(departed.enabled, true);
eq(removeContact(departed, A).groups.map(group => group.id), ["friends"], "other contacts keep a group alive");
let removed = remove(departed, "friends");
eq(removed, { version: 1, enabled: true, groups: [], assignments: {}, order: [U], collapsed: [U] }, "deleting a group unassigns all contacts and cleans order/collapse");
eq(removeContact(create(empty, A, "only", "Only"), A), empty, "deleting final contact removes its group");
eq(assign(create(empty, A, "only", "Only"), A, U), empty, "system assignment is represented by absence");
let replacement = create(create(empty, A, "old", "Old"), A, "new", "New");
eq(replacement.groups, [{ id: "new", name: "New" }], "creating with an already assigned first contact prunes the old group");
const polluted = JSON.parse('{"__proto__":"work","constructor":"work","'+A+'":"work"}');
const corrupt = { version: 1, enabled: true, groups: [{ id: U, name: "Fake" }, { id: "work", name: " Work " }, { id: "dup", name: "WORK" }, { id: "friends", name: "Friends" }, { id: "empty", name: "Empty" }, { id: "system", name: "Ungrouped" }], assignments: { ...polluted, [B.toLowerCase()]: "friends", [C]: "missing", "not-a-key": "work" }, order: ["friends", "missing", "friends", U, "work", "empty"], collapsed: ["empty", "friends", U, "friends", "missing"] };
const repaired = normalize(freeze(corrupt));
eq(repaired.groups, [{ id: "work", name: "Work" }, { id: "friends", name: "Friends" }]);
eq(repaired.assignments, { [A]: "work", [B]: "friends" }, "invalid and prototype keys cannot enter assignments");
eq(repaired.order, ["friends", U, "work"]);
eq(repaired.collapsed, ["friends", U]);
eq(normalize({ ...corrupt, order: [], collapsed: "all" }).order, [U, "work", "friends"], "missing order includes system and all occupied groups exactly once");
eq(normalize(repaired), repaired, "normalization is idempotent");
const profileOne = normalize(JSON.parse(JSON.stringify(repaired)));
const profileTwo = normalize(JSON.parse(JSON.stringify(repaired)));
const altered = remove(assign(profileOne, A, "friends"), "friends");
eq(profileTwo, repaired, "serialized profile boundary creates independent objects");
eq(profileOne, repaired, "all operations preserve their input object");
eq(altered.groups, []);
eq(normalize(JSON.parse(JSON.stringify(moved))), moved, "restart restores visibility, identities, order and collapse");
eq(normalize(create(empty, C, "hidden", "Hidden")).groups, [{ id: "hidden", name: "Hidden" }], "no transient UI contact snapshot prunes saved identities");
eq(state.assignments, { [A]: "work" }, "frozen source state was not mutated");
console.log(`contact groups migration, lifecycle, corruption, order, and profile isolation: ${assertions} assertions passed`);
