import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { importTypeScriptModule } from "./import-typescript-module.mjs";

const { createNotificationSoundPlayer, DEFAULT_NOTIFICATION_SOUND, normalizeNotificationSound } = await importTypeScriptModule(new URL("../src/notificationSound.ts", import.meta.url));
assert.deepEqual(DEFAULT_NOTIFICATION_SOUND, { notifySound: false, notificationVolume: 0.7 });
assert.deepEqual(normalizeNotificationSound({}), DEFAULT_NOTIFICATION_SOUND, "old profiles receive disabled sound by default");
for (const value of [null, "true", 1, false]) assert.equal(normalizeNotificationSound({ notifySound: value }).notifySound, false);
assert.equal(normalizeNotificationSound({ notifySound: true }).notifySound, true);
for (const volume of [null, "0.5", Number.NaN, Infinity, -Infinity]) assert.equal(normalizeNotificationSound({ notificationVolume: volume }).notificationVolume, 0.7);
for (const [input, expected] of [[0, 0], [0.25, 0.25], [1, 1], [-1, 0], [2, 1]]) assert.equal(normalizeNotificationSound({ notificationVolume: input }).notificationVolume, expected);

let foreground = true;
let created = 0;
let played = 0;
let paused = 0;
let loaded = 0;
let failPlay = false;
const audio = { currentTime: 0.4, volume: 1, src: "signal.wav", play() { played++; return failPlay ? Promise.reject(new Error("decoder denied")) : Promise.resolve(); }, pause() { paused++; }, load() { loaded++; } };
const player = createNotificationSoundPlayer(() => { created++; return audio; }, () => foreground);
player.play(0.8);
assert.equal(created, 0, "foreground events do not even allocate an audio element");
foreground = false;
for (const value of [0, -1, NaN, Infinity, null, "0.5"]) player.play(value);
assert.equal(created, 0, "muted, invalid and non-finite volumes cannot start playback");
player.play(0.25);
assert.deepEqual({ created, played, volume: audio.volume, time: audio.currentTime }, { created: 1, played: 1, volume: 0.25, time: 0 });
audio.currentTime = 0.3;
player.play(4);
assert.deepEqual({ created, played, volume: audio.volume, time: audio.currentTime }, { created: 1, played: 2, volume: 1, time: 0 }, "a burst restarts one bounded voice at the capped volume");
foreground = true;
player.stop();
player.play(0.5);
assert.equal(played, 2, "returning to foreground stops the sound and prevents another playback");
assert.equal(paused, 1);
foreground = false;
failPlay = true;
player.play(0.5);
await new Promise((resolve) => setImmediate(resolve));
assert.equal(played, 3, "play rejection is consumed without breaking the next native event");
player.dispose();
assert.deepEqual({ paused, loaded, src: audio.src }, { paused: 2, loaded: 1, src: "" }, "unmount releases decoder data and stops playback");
player.play(1); player.dispose();
assert.equal(played, 3, "late messages cannot restart a disposed sound player");
assert.equal(loaded, 1, "dispose is idempotent");
const unavailable = createNotificationSoundPlayer(() => { throw new Error("audio unavailable"); }, () => false);
assert.doesNotThrow(() => unavailable.play(1), "audio construction failure does not escape the event listener");
unavailable.dispose();
const syncFailure = createNotificationSoundPlayer(() => ({ ...audio, play() { throw new Error("synchronous decoder failure"); } }), () => false);
assert.doesNotThrow(() => syncFailure.play(1));
syncFailure.dispose();

const signal = await readFile(new URL("../src/assets/signal.wav", import.meta.url));
assert.equal(createHash("sha256").update(signal).digest("hex"), "6f72580f3f64e6ff272a048230121f1dc5e7c26b6bc5fe410085a48bef68f7e7");
console.log("notification sound defaults, volume, foreground, lifecycle and exact WAV: PASS");
