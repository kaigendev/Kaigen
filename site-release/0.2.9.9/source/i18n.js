export const LANGUAGE_ORDER = ['ru', 'en', 'zh', 'ja', 'es', 'fr', 'hi'];

export const localeByLanguage = Object.freeze({
  ru: 'ru-RU',
  en: 'en-US',
  zh: 'zh-CN',
  ja: 'ja-JP',
  es: 'es-ES',
  fr: 'fr-FR',
  hi: 'hi-IN'
});

export function resolveLanguage(savedLanguage, preferredLanguages = []) {
  if (LANGUAGE_ORDER.includes(savedLanguage)) return savedLanguage;
  for (const candidate of preferredLanguages) {
    const base = String(candidate || '').trim().toLowerCase().split(/[-_]/)[0];
    if (LANGUAGE_ORDER.includes(base)) return base;
  }
  return 'ru';
}

